import {readFile,writeFile} from 'node:fs/promises';
import {createHash} from 'node:crypto';
import {READY_WORDS} from '../app/course-content.js';
import {sentenceMeaning} from '../app/sentence-meanings.js';
import {ACTIVITY_PROFILES} from '../app/guided-activity-profiles.js';
import {validateGuidedPlans} from './guided-activity-validation.mjs';
const root=new URL('../',import.meta.url);
const input=await readFile(new URL('data/vocabulary/guided-word-plans.json',root),'utf8');
const scenesText=await readFile(new URL('data/vocabulary/guided-scenes.json',root),'utf8');
const document=JSON.parse(input),scenes=JSON.parse(scenesText).entries;
const plans=validateGuidedPlans(READY_WORDS,document,scenes,ACTIVITY_PROFILES,sentenceMeaning);
const profileCode=await readFile(new URL('app/guided-activity-profiles.js',root),'utf8');
const activityCode=await readFile(new URL('app/guided-activities.js',root),'utf8');
const fingerprint=createHash('sha256').update(input).update(scenesText).update(profileCode).update(activityCode).digest('hex');
const result='// Generated by scripts/compile-guided-activities.mjs. Do not edit.\nexport const GUIDED_PLAN_FINGERPRINT='+JSON.stringify(fingerprint)+';\nexport const GUIDED_WORD_PLANS='+JSON.stringify(plans)+';\n';
const out=new URL('app/guided-word-plans.js',root);
if(process.argv.includes('--check')){
 if(await readFile(out,'utf8')!==result)throw Error('Generated guided plans are stale; run node scripts/compile-guided-activities.mjs');
}else await writeFile(out,result);
console.log(`Validated ${READY_WORDS.length} guided word plans, ${Object.keys(ACTIVITY_PROFILES).length} strategies, ${Object.keys(scenes).length} specific scenarios.`);

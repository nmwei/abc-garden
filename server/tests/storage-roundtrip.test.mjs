import test from 'node:test';
import assert from 'node:assert/strict';
import {createApp} from '../app.mjs';
import {learningSnapshot} from '../../tests/fixtures/learning-snapshot.mjs';
import {DATA} from '../../web/app/learning-data.js';

test('all learning domains survive local capture, API, SQLite, checkpoint and account restoration',async t=>{
 const app=await createApp({origin:'http://localhost:4173',secret:'isolated-full-storage-test-secret',secure:false,unitCostFen:6,sendSms:async()=> '817264'});
 t.after(()=>app.close());
 const headers={origin:'http://localhost:4173','x-garden-client':'web-v1'};
 const call=(url,method='GET',payload)=>app.inject({url,method,headers,...(payload?{payload}:{})});
 const sms=await call('/api/auth/sms','POST',{phone:'13800138888',purpose:'register'});
 assert.equal(sms.statusCode,200,sms.body);
 const registered=await call('/api/auth/register','POST',{phone:'13800138888',challengeId:sms.json().challengeId,code:'817264',username:'StorageTest',password:'12345678',consent:true});
 assert.equal(registered.statusCode,200,registered.body);
 headers.cookie=registered.cookies.map(c=>`${c.name}=${c.value}`).join('; ');
 const account=registered.json().account,url=`/api/profiles/${account.profileId}/abc`;
 const original=Object.getOwnPropertyDescriptor(globalThis,'localStorage');
 const values=new Map();globalThis.localStorage={getItem:key=>values.get(key)??null,setItem:(key,value)=>values.set(key,value),removeItem:key=>values.delete(key)};
 t.after(()=>original?Object.defineProperty(globalThis,'localStorage',original):delete globalThis.localStorage);
 const store=await import('../../web/app/account-storage.js?roundtrip');
 const expected=learningSnapshot();
 for(const [key,value] of Object.entries(expected.data))store.learningStorage.setItem(key,JSON.stringify(value));
 const sent=store.captureArchive();assert.deepEqual(sent,expected);
 const saved=await call(url,'PUT',{revision:0,snapshot:sent,checkpoint:true});assert.equal(saved.statusCode,200,saved.body);
 const received=(await call(url)).json();assert.deepEqual(received.snapshot,expected);
 const history=(await call(url+'/history')).json().versions;
 assert.equal(history.length,1);
 const checkpoint=(await call(url+'/history/'+history[0].revision)).json();assert.deepEqual(checkpoint.snapshot,expected);
 store.activateArchive(account.id,received.snapshot,{revision:received.revision});
 for(const [key,value] of Object.entries(expected.data))assert.deepEqual(JSON.parse(store.learningStorage.getItem(key)),value,key);
 const before=store.localSyncState();
 assert.throws(()=>store.learningStorage.setItem('forgotten-setting','{}'));
 assert.throws(()=>store.learningStorage.setItem(DATA.content,JSON.stringify({...expected.data[DATA.content],repeats:99})));
 assert.deepEqual(store.localSyncState(),before);
 store.activateArchive('guest',{version:1,subject:'abc',data:{}});
 assert.equal(store.learningStorage.getItem(DATA.listening),null);
 assert.deepEqual(store.retainedArchive(account.id).snapshot,expected);
});

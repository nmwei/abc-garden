import {test,expect} from '@playwright/test';
import {openParents,unlockParents} from './parent-helpers.js';
const edit=page=>page.locator('#selection-results').locator('[data-learning=edit-meaning][data-word=walk]');
test('parent gloss editing persists across reload, drives search and loop speech, and restores default',async({page})=>{
 await page.addInitScript(()=>{
  if(!localStorage.getItem('abc-module-content-v1'))localStorage.setItem('abc-module-content-v1',JSON.stringify({letters:'EF',selectedWordIds:['walk']}));
  window.spoken=[];Object.defineProperty(window,'speechSynthesis',{value:{getVoices:()=>[],speak:u=>{if(u.volume!==0){window.spoken.push(u.text);queueMicrotask(()=>u.onend?.());}},cancel:()=>{}}});
 });
 await openParents(page,true);await page.locator('#selection-query').fill('walk');await edit(page).click();
 await page.getByLabel('中文释义',{exact:true}).fill('散步');await page.getByLabel('英文例句',{exact:true}).fill('We walk home.');await page.getByLabel('例句中文',{exact:true}).fill('我们走回家。');await page.getByRole('button',{name:'保存内容',exact:true}).click();
 await expect(page.locator('#word-meaning-dialog')).not.toBeVisible();await expect(edit(page)).toContainText('散步');
 await page.reload();await unlockParents(page);await page.locator('#selection-query').fill('散步');await expect(edit(page)).toBeVisible();
 await page.getByRole('button',{name:'看图学词',exact:true}).click();
 await expect(page.locator('.learning-panel')).toContainText('散步');await expect(page.locator('.sentence')).toHaveText('We walk home.');
 await expect(page.locator('.sentence-meaning')).toHaveText('我们走回家。');
 await page.getByRole('button',{name:'听句子',exact:true}).click();await expect.poll(()=>page.evaluate(()=>window.spoken)).toEqual(['We walk home.']);
 await page.getByRole('button',{name:'朗读中文译文'}).click();await expect.poll(()=>page.evaluate(()=>window.spoken)).toEqual(['We walk home.','我们走回家。']);await page.evaluate(()=>window.spoken=[]);
 await page.locator('#word-search').fill('散步');await expect(page.locator('.word-list [data-course=word]')).toHaveCount(1);
 await page.getByRole('button',{name:'循环听 · 1 个词',exact:true}).click();
 await page.locator('#garden-audio').evaluate(a=>a.dispatchEvent(new Event('ended')));
 await expect.poll(()=>page.evaluate(()=>window.spoken)).toEqual(['散步']);
 await openParents(page);await page.locator('#selection-query').fill('walk');await edit(page).click();
 await page.getByRole('button',{name:'恢复默认',exact:true}).click();await expect(edit(page)).toContainText('走');
 expect(await page.evaluate(()=>JSON.parse(localStorage.getItem('abc-module-content-v1')).wordMeanings)).toEqual({});
});
test('cancel, empty input and failed storage never replace the saved gloss',async({page})=>{
 await openParents(page,true);await page.locator('#selection-query').fill('walk');await edit(page).click();
 await page.getByLabel('中文释义',{exact:true}).fill('散步');await page.getByRole('button',{name:'取消',exact:true}).click();
 await edit(page).click();await expect(page.getByLabel('中文释义',{exact:true})).toHaveValue('走');
 await page.getByLabel('中文释义',{exact:true}).fill('   ');await page.getByRole('button',{name:'保存内容',exact:true}).click();await expect(page.locator('#word-meaning-status')).toContainText('请填写');
 await page.getByLabel('中文释义',{exact:true}).fill('散步');
 await page.evaluate(()=>{Storage.prototype.setItem=function(){throw new Error('quota');};});
 await page.getByRole('button',{name:'保存内容',exact:true}).click();
 await expect(page.locator('#word-meaning-status')).toContainText('保存失败');await expect(page.getByLabel('中文释义',{exact:true})).toHaveValue('散步');
 await page.screenshot({path:'test-results/meaning-editor.png',fullPage:false});
 await page.getByRole('button',{name:'取消',exact:true}).click();await expect(edit(page)).toContainText('走');
});
test('search-only editor prefills default translation and preserves it on gloss-only save',async({page})=>{
 await openParents(page,true);
 await expect(page.locator('#selection-results button')).toHaveCount(0);
 await expect(page.locator('#word-editor select')).toHaveCount(0);
 await page.locator('#selection-query').fill('zzzzzz');await expect(page.locator('#selection-results')).toContainText('没有找到匹配');
 await page.locator('#selection-query').fill('apple');
 await page.locator('[data-learning=edit-meaning][data-word=apple]').click();
 await expect(page.getByLabel('英文例句',{exact:true})).toHaveValue('I like apples.');
 await expect(page.getByLabel('例句中文',{exact:true})).toHaveValue('我喜欢苹果。');
 await page.getByLabel('中文释义',{exact:true}).fill('大苹果');await page.getByRole('button',{name:'保存内容',exact:true}).click();
 await page.reload();await unlockParents(page);await page.locator('#selection-query').fill('apple');await page.locator('[data-learning=edit-meaning][data-word=apple]').click();
 await expect(page.getByLabel('例句中文',{exact:true})).toHaveValue('我喜欢苹果。');
 await page.getByRole('button',{name:'恢复默认',exact:true}).click();await page.locator('[data-learning=edit-meaning][data-word=apple]').click();
 await expect(page.getByLabel('中文释义',{exact:true})).toHaveValue('苹果');await expect(page.getByLabel('例句中文',{exact:true})).toHaveValue('我喜欢苹果。');
 await page.screenshot({path:'test-results/default-translation.png'});
});

const phraseProfiles=new Set(['language','tense','discourse','degree','frequency','social-language']);
export function activityFor(word){
 const original=CATALOG_BY_ID.get(word.id),plan=GUIDED_WORD_PLANS[word.id];
 const changedMeaning=!original||guidedSense(original)!==guidedSense(word);
 const modelZh=word.sentenceZh||sentenceMeaning(word.sentence||'');
 if(changedMeaning||!plan){
  const manual=renderProfile('concept',{focus:word.zh,scene:modelZh});
  return {...manual,type:'context',source:'custom',profile:'custom',responseMode:'word',focus:word.zh,contextual:false,modelText:'',modelZh:'',
   scene:'家长已修改词义，请先用中文把当前意思讲清，再选择相符的动作或情境；不自动沿用原来义项的玩法。'};
 }
 const editedExample=word.sentence!==original.sentence||modelZh!==(original.sentenceZh||sentenceMeaning(original.sentence));
 const scene=editedExample?modelZh:plan.scene||modelZh;
 const profile=renderProfile(plan.profile,{focus:plan.focus,scene});
 const action=['motor','emotion','social-action','learning-concept'].includes(plan.profile)&&actions[word.id];
 const row=action||concrete[word.id];
 const tailored=row?{setup:row[0],teach:row[1],listen:row[2],transfer:row[3]}:{};
 const result={...profile,...tailored,...plan,scene,source:row||plan.scene?'curated':'profile',
  modelText:editedExample?word.sentence:plan.modelText||word.sentence,
  modelZh:editedExample?modelZh:plan.modelZh||modelZh,
  modelCredit:editedExample||plan.modelText?'':word.sentenceCredit||'',
 };
 result.type=action||result.type==='action'?'action':result.cueMode==='picture'?'concrete':'context';
 result.pictureChoice=result.pictureChoice===true&&!word.pictureCue;
 if(word.pictureCue&&result.cueMode==='picture')result.cueMode='live';
 result.responseMode=phraseProfiles.has(result.profile)?'phrase':'word';
 return result;
}
